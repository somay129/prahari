import uuid
import hashlib
import json
import os
from datetime import datetime
from pathlib import Path
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, func
from backend.db.models import EvidenceRecord

ENGINE_VERSION = "PRAHARI-1.0.0"
PDF_DIR = Path("evidence_pdfs")


def _gen_case_id(module: str) -> str:
    prefix = {"currency": "CUR", "scam": "SCM", "fraud": "FRD", "citizen": "CTZ"}.get(module, "EVD")
    ts = datetime.utcnow().strftime("%Y%m%d")
    uid = str(uuid.uuid4())[:6].upper()
    return f"{prefix}-{ts}-{uid}"


def _content_hash(payload: dict) -> str:
    raw = json.dumps(payload, sort_keys=True, default=str)
    return hashlib.sha256(raw.encode()).hexdigest()


async def create_evidence(
    db: AsyncSession,
    module: str,
    verdict: str,
    confidence: float,
    decision_trace: dict,
    content_payload: dict,
    metadata: dict | None = None,
) -> EvidenceRecord:
    rec = EvidenceRecord(
        id=str(uuid.uuid4())[:8].upper(),
        case_id=_gen_case_id(module),
        source_module=module,
        timestamp=datetime.utcnow(),
        content_hash=_content_hash(content_payload),
        engine_version=ENGINE_VERSION,
        verdict=verdict,
        confidence=confidence,
        decision_trace=decision_trace,
        metadata_=metadata or {},
    )
    db.add(rec)
    await db.commit()
    await db.refresh(rec)
    return rec


async def list_evidence(db: AsyncSession, module: str | None = None, limit: int = 100, offset: int = 0):
    q = select(EvidenceRecord).order_by(EvidenceRecord.timestamp.desc())
    if module:
        q = q.where(EvidenceRecord.source_module == module)
    count_q = select(func.count()).select_from(EvidenceRecord)
    if module:
        count_q = count_q.where(EvidenceRecord.source_module == module)
    total = (await db.execute(count_q)).scalar_one()
    records = (await db.execute(q.limit(limit).offset(offset))).scalars().all()
    return total, records


async def get_evidence(db: AsyncSession, evidence_id: str) -> EvidenceRecord | None:
    return (await db.execute(select(EvidenceRecord).where(EvidenceRecord.id == evidence_id))).scalar_one_or_none()


def generate_pdf(record: EvidenceRecord) -> bytes:
    from fpdf import FPDF
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "PRAHARI EVIDENCE RECORD", ln=True, align="C")
    pdf.set_font("Helvetica", "", 8)
    pdf.cell(0, 6, "DEMO DATA — synthetic, for evaluation only", ln=True, align="C")
    pdf.ln(4)
    pdf.set_font("Courier", "B", 11)
    pdf.cell(0, 8, f"Case ID: {record.case_id}", ln=True)
    pdf.cell(0, 8, f"Evidence ID: {record.id}", ln=True)
    pdf.set_font("Courier", "", 10)
    pdf.cell(0, 7, f"Module: {record.source_module.upper()}", ln=True)
    pdf.cell(0, 7, f"Timestamp (UTC): {record.timestamp.isoformat()}", ln=True)
    pdf.cell(0, 7, f"Engine Version: {record.engine_version}", ln=True)
    pdf.cell(0, 7, f"Verdict: {record.verdict}", ln=True)
    pdf.cell(0, 7, f"Confidence: {record.confidence:.1%}", ln=True)
    pdf.cell(0, 7, f"Content Hash (SHA-256):", ln=True)
    pdf.cell(0, 7, f"  {record.content_hash}", ln=True)
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Decision Trace", ln=True)
    pdf.set_font("Courier", "", 9)
    trace_text = json.dumps(record.decision_trace, indent=2, default=str)
    for line in trace_text.split("\n")[:60]:
        pdf.cell(0, 5, line[:100], ln=True)
    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 8)
    pdf.cell(0, 6, "This record is generated by PRAHARI Detection Engine and is intended for official use only.", ln=True)
    return bytes(pdf.output())
